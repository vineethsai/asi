#!/usr/bin/env node
/**
 * Print the dataset counts block used in README.md (`npm run counts`).
 *
 *   npm run counts                     # print the block to stdout
 *   npm run counts -- --write README.md  # replace the block between
 *                                        # <!-- counts:start --> and <!-- counts:end -->
 *
 * Every number is computed from the data modules, so the README cannot drift
 * from the data.
 */
import fs from "fs";
import path from "path";
import { loadTsModule, projectRoot } from "./check-data-integrity.js";

const START = "<!-- counts:start -->";
const END = "<!-- counts:end -->";

function countNodes(nodes) {
  return (nodes ?? []).reduce((n, node) => n + 1 + countNodes(node.children), 0);
}

function buildBlock() {
  const security = loadTsModule("src/components/components/securityData.ts");
  const aisvs = loadTsModule("src/data/aisvs.ts");
  const top10 = loadTsModule("src/components/components/owaspAgenticTop10Data.ts");
  const cisco = loadTsModule("src/components/components/ciscoTaxonomyData.ts");
  const aiuc1 = loadTsModule("src/components/components/aiuc1Data.ts");
  const aivss = loadTsModule("src/components/components/aivssCalcData.ts");
  const framework = loadTsModule("src/components/components/frameworkData.ts");
  const architectures = loadTsModule("src/components/components/architecturesData.ts");
  const nist = loadTsModule("src/data/nistAisvsRemap.ts");
  const atlas = loadTsModule("src/data/atlasCrosswalk.ts");
  const { SOURCES } = loadTsModule("src/data/sources.ts");

  const s = aisvs.aisvsStats;
  const c = cisco.getTaxonomyStats();
  const a = aiuc1.getAiuc1Stats();
  const nistEntries = Object.values(nist.NIST_AISVS_REMAP);
  const nistOrg = nistEntries.filter((e) => e.organizational).length;
  const kcTop = framework.frameworkData.length;

  const rows = [
    [
      `[${SOURCES.threats.name}](${SOURCES.threats.url})`,
      SOURCES.threats.version,
      `${Object.keys(security.threatsData).length} threats (T1–T${Object.keys(security.threatsData).length})`,
    ],
    [
      "Controls (editorial, mapped to AISVS)",
      SOURCES.controls.version,
      `${Object.keys(security.mitigationsData).length} controls`,
    ],
    [
      `[${SOURCES.top10.name}](${SOURCES.top10.url})`,
      SOURCES.top10.version,
      `${top10.agenticTop10Data.length} risks (ASI01–ASI10)`,
    ],
    [
      `[OWASP AISVS](${SOURCES.aisvs.url})`,
      s.version,
      `${s.chapters} chapters, ${s.sections} sections, ${s.requirements} requirements (L1 ${s.byLevel[0]} / L2 ${s.byLevel[1]} / L3 ${s.byLevel[2]})`,
    ],
    [
      `[OWASP AIVSS](${SOURCES.aivss.url})`,
      SOURCES.aivss.version,
      `${aivss.AIVSS_CORE_RISK_NAMES.length} core risks, ${aivss.agenticRiskFactors.length} agentic risk factors`,
    ],
    [
      `[${SOURCES.cisco.name}](${SOURCES.cisco.url})`,
      cisco.CISCO_TAXONOMY_VERSION,
      `${c.objectiveGroups} objectives, ${c.techniques} techniques, ${c.subTechniques} sub-techniques`,
    ],
    [
      "MITRE ATLAS crosswalk (from Cisco's ATLAS mappings)",
      atlas.ATLAS_RELEASE,
      `${atlas.atlasCrosswalk.filter((r) => r.kind !== "tactic").length} ATLAS techniques and sub-techniques (+${atlas.atlasCrosswalk.filter((r) => r.kind === "tactic").length} tactic) linked to Cisco, OWASP ASI and site threats`,
    ],
    [
      `[AIUC-1](${SOURCES.aiuc1.url})`,
      aiuc1.AIUC1_VERSION,
      `${a.active} active requirements (${a.requirements} ids, ${a.retired} retired), ${a.controls} controls`,
    ],
    [
      `[NIST AI RMF](${SOURCES.nist.url}) → AISVS`,
      "1.0",
      `${nistEntries.length} subcategories (${nistEntries.length - nistOrg} mapped, ${nistOrg} organizational)`,
    ],
    [
      `[${SOURCES.kc.name}](${SOURCES.kc.url})`,
      SOURCES.kc.version,
      `${kcTop} key components, ${countNodes(framework.frameworkData) - kcTop} sub-components`,
    ],
    [
      "Architecture patterns (editorial)",
      SOURCES.architectures.version,
      `${Object.keys(architectures.architecturesData).length} patterns`,
    ],
  ];

  const lines = [
    START,
    "<!-- Generated by `npm run counts -- --write README.md`; do not edit by hand. -->",
    "",
    "| Dataset | Version | Contents |",
    "| --- | --- | --- |",
    ...rows.map((r) => `| ${r.join(" | ")} |`),
    "",
    `Data last checked against primary sources: ${Object.values(SOURCES)
      .map((x) => x.retrievedAt)
      .sort()
      .pop()}.`,
    END,
  ];
  return lines.join("\n");
}

const block = buildBlock();
const writeIndex = process.argv.indexOf("--write");
if (writeIndex === -1) {
  console.log(block);
} else {
  const target = path.resolve(projectRoot, process.argv[writeIndex + 1] || "README.md");
  const current = fs.readFileSync(target, "utf8");
  const start = current.indexOf(START);
  const end = current.indexOf(END);
  if (start === -1 || end === -1 || end < start) {
    console.error(`${path.relative(projectRoot, target)} has no ${START} … ${END} markers`);
    process.exit(1);
  }
  const next = current.slice(0, start) + block + current.slice(end + END.length);
  fs.writeFileSync(target, next);
  console.log(`Updated counts in ${path.relative(projectRoot, target)}`);
}
